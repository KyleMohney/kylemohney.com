/**
 * NY STATE COMPLIANCE CHECK
 * Check if a zipcode is in New York state
 * @param {string} zipcode - The zipcode to check
 * @returns {boolean} true if zipcode is in NY, false otherwise
 */
function isNewYorkZipcode(zipcode) {
  if (!zipcode) return false;
  const cleanZip = zipcode.trim().slice(0, 5);
  return NY_STATE_ZIPCODES.has(cleanZip);
}

/**
 * NY STATE COMPLIANCE BLOCK - HARD ENFORCEMENT
 * Prevents ALL submissions from NY state residents
 * @param {string} zipcode - The zipcode to check
 * @param {string} submissionType - Type of submission (e.g., 'project', 'practitioner_profile')
 * @returns {Object} { allowed: boolean, message: string }
 */
function validateNYComplianceBlock(zipcode, submissionType = 'project') {
  const isNY = isNewYorkZipcode(zipcode);
  
  if (isNY) {
    console.error(`[NY COMPLIANCE] š–ï¸ BLOCKED: ${submissionType} submission from NY zipcode ${zipcode}`);
    console.error('[NY COMPLIANCE] This is a legal mandate - submission cannot be processed');
    
    return {
      allowed: false,
      message: `We're currently unable to serve clients in New York state. We apologize for any inconvenience. Please contact support@rootedvitality.com for more information.`,
      reason: 'ny_state_restriction'
    };
  }
  
  return {
    allowed: true,
    message: null,
    reason: null
  };
}

/**
 * VALIDATE BEFORE SUBMISSION
 * Call this BEFORE any form submission for client/practitioner work
 * @param {Object} data - Form data object
 * @param {string} dataType - 'client' or 'practitioner'
 * @returns {Object} { valid: boolean, error: string|null }
 */
function validateNYStateCompliance(data, dataType = 'client') {
  // Extract state and zipcode
  const state = data.state?.trim()?.toUpperCase() || '';
  const zipcode = data.zipcode?.trim() || '';
  
  // Check by state code
  if (state === 'NY' || state === 'NEW YORK') {
    return {
      valid: false,
      error: `We're unable to serve practitioners in New York state at this time. This is due to regulatory requirements. Please contact support for more information.`
    };
  }
  
  // Check by zipcode
  if (zipcode) {
    const nyCheck = validateNYComplianceBlock(zipcode, dataType);
    if (!nyCheck.allowed) {
      return {
        valid: false,
        error: nyCheck.message
      };
    }
  }
  
  return {
    valid: true,
    error: null
  };
}

/**
 * GUARDIAN FUNCTION - Never allow NY submissions
 * Should be called at the LAST POSSIBLE MOMENT before database insert
 * @param {string} zipcode - The zipcode being submitted
 * @param {string} state - The state being submitted
 * @param {Function} successCallback - What to do if validation passes
 * @param {Function} errorCallback - What to do if validation fails
 */
async function guardianCheckBeforeSubmit(zipcode, state, successCallback, errorCallback) {
  // Double-check: is this NY?
  if (isNewYorkZipcode(zipcode) || state?.toUpperCase() === 'NY') {
    console.error('[NY COMPLIANCE GUARDIAN] ðŸš« SUBMISSION BLOCKED - NY STATE DETECTED');
    console.error('[NY COMPLIANCE GUARDIAN] Zipcode:', zipcode);
    console.error('[NY COMPLIANCE GUARDIAN] State:', state);
    
    // Call error callback
    if (typeof errorCallback === 'function') {
      errorCallback({
        code: 'NY_COMPLIANCE_VIOLATION',
        message: 'We are unable to process requests from New York state at this time.',
        timestamp: new Date().toISOString()
      });
    }
    
    return false;
  }
  
  // Validation passed - execute success callback
  if (typeof successCallback === 'function') {
    await successCallback();
  }
  
  return true;
}

